// index.js - the price plugin's host part (magpie.page + main).
//
// The page is sandboxed: connect-src 'none', no fetch, no file access. It can
// only save through magpie.options.set, which writes plugins.json. Nothing used
// to apply those saves except a CLI run by hand (`magpie-models-price apply`),
// so a price edited in the page did not reach settings.json until the user
// remembered to run it.
//
// This module is that apply step, run by magpie itself: a plugin with a main
// gets a host (internal/plugin/page.go: hosted = main or exports present), and
// magpie starts it when the page is opened (pluginpage.go pageHost). It does two
// things the page cannot, on a timer, and writes the result where the page can
// read it with a <script src>:
//
//   - applies a save the page made (apply-options.js), writing only the keys
//     that save changed into magpie's settings.json;
//   - rebuilds page/models-data.js (page-data.js), the model list the page draws.
//
// Both write files, never plugins.json: magpie restarts the host on every
// plugins.json change (plugin.SetOptions), so recording progress there would
// restart the very host recording it.
//
// No provider, no middleware: config() answers nothing, so magpie lists no
// provider for this plugin.
const fs = require('node:fs');
const path = require('node:path');

const matcher = require('./matcher');
const applier = require('./apply-options');
const pageData = require('./page-data');

const SELF_ROOT = __dirname;
// The page folder magpie actually serves. It is this package's own page/ when
// magpie loaded the package from its plugins folder, which is the normal case;
// the override exists for a checkout that is testing the host against another
// folder (check.js), the same way the CLI takes it.
const PAGE_DIR = process.env.MAGPIE_MODELS_PRICE_PAGE_DIR
  ? path.resolve(process.env.MAGPIE_MODELS_PRICE_PAGE_DIR)
  : path.join(SELF_ROOT, 'page');
const STATUS_FILE = path.join(PAGE_DIR, 'price-status.js');
const MODELS_FILE = path.join(PAGE_DIR, 'models-data.js');
// The usage snapshot the page reads instead of usage:day: that read lists only
// twelve models per agent, so its per-model numbers never added up to its own
// total (see page-data.js).
const USAGE_FILE = path.join(PAGE_DIR, 'usage-data.js');

// How often the host looks for a save to apply and for a stale model list.
// A page save causes no event here (magpie keeps plugins.json to itself), so
// the loop is a poll; 2s is fast enough to feel immediate after a save.
const TICK_MS = Number(process.env.MAGPIE_MODELS_PRICE_TICK_MS) || 2000;

let timer = null;
let ticking = false;
let lastSignature = '';

// writeIfChanged replaces a generated page script only when its content
// differs: the page re-reads these files by <script src>, and a rewrite with
// the same bytes would still cost a revalidation on every tick.
function writeIfChanged(file, text) {
  try {
    if (fs.existsSync(file)) {
      const before = fs.readFileSync(file, 'utf8');
      if (before === text) return false;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
    const tmp = file + '.' + process.pid + '.tmp';
    fs.writeFileSync(tmp, text, 'utf8');
    fs.renameSync(tmp, file);
    return true;
  } catch (error) {
    console.error('[magpie-models-price] cannot write ' + path.basename(file) + ': ' + error.message);
    return false;
  }
}

// statusScript is what the page reads as window.__MAGPIE_PRICE_STATUS__: the
// save it just made, whether that save reached settings.json, and the model
// list's age. The page cannot ask the host anything (no fetch), so this file
// is the answer.
function statusScript(status) {
  return '// Generated by the magpie-models-price host part. Do not edit.\n' +
    'window.__MAGPIE_PRICE_STATUS__ = ' + JSON.stringify(status, null, 2) + ';\n';
}

// modelsAge is how long ago page/models-data.js was written, or null when the
// page has none yet: the page shows a hint instead of an empty list.
function modelsAge() {
  try {
    return Math.max(0, Math.round((Date.now() - fs.statSync(MODELS_FILE).mtimeMs) / 1000));
  } catch {
    return null;
  }
}

// refreshModels rebuilds the page's model list when it is missing or older
// than the files it is built from. page-data.js decides that itself and writes
// only when needed, so this can run on every tick.
function refreshModels(force) {
  try {
    const built = pageData.writePageData(SELF_ROOT, { pageDir: PAGE_DIR, force: !!force });
    if (built && built.ok) return { ok: true, models: built.models, generated: !!built.generated };
    return { ok: false, error: (built && built.error) || 'model list build failed' };
  } catch (error) {
    return { ok: false, error: error.message };
  }
}

// refreshUsage rewrites the page's usage snapshot when this machine logged a
// call since the last tick. page-data.js keeps the last one in memory and
// compares the file's size and mtime, so a quiet machine reads nothing.
function refreshUsage() {
  try {
    const built = pageData.writeUsageData(SELF_ROOT, { pageDir: PAGE_DIR });
    if (built && built.ok) return { ok: true, requests: built.requests, generated: !!built.generated };
    return { ok: false, error: (built && built.error) || 'usage snapshot failed' };
  } catch (error) {
    return { ok: false, error: error.message };
  }
}

// tick applies every save this machine has not applied yet, refreshes the model
// list, and writes the page's status script. It never throws: a host that dies
// on one bad file stops applying every later save.
function tick() {
  if (ticking) return null;
  ticking = true;
  const status = { v: 1, at: new Date().toISOString(), applies: [], models: null, error: '' };
  try {
    let results = [];
    try {
      results = applier.applyPendingOptions();
    } catch (error) {
      status.error = 'apply failed: ' + error.message;
    }
    for (const item of results) {
      const r = item.result || {};
      status.applies.push({
        spec: item.spec,
        token: item.token,
        applied: !!r.applied,
        reason: r.reason || '',
        prices: r.prices || 0,
        peakProviders: r.peakProviders || 0,
        error: r.error || r.peakError || ''
      });
    }
    const models = refreshModels(false);
    status.models = { ok: !!models.ok, count: models.models || 0, generated: !!models.generated, ageSec: modelsAge(), error: models.error || '' };
    const usage = refreshUsage();
    status.usage = { ok: !!usage.ok, requests: usage.requests || 0, generated: !!usage.generated, error: usage.error || '' };
    // What settings.json actually holds for the prices the page saved: the page
    // says 'saved', this says whether magpie bills that price.
    try {
      // Only priceChanges is a save; customPrices is the stored map, and
      // verifying against it would report the whole table as "applied" even
      // when this save changed nothing (same fallback as apply-options.js).
      const options = matcher.readPluginOptions(SELF_ROOT) || {};
      const saved = options.priceChanges && typeof options.priceChanges === 'object'
        ? options.priceChanges
        : {};
      status.verify = matcher.verifyCustomPrices(saved);
      status.appliedToken = applier.readApplied().token || '';
    } catch (error) {
      status.verify = { checked: 0, matched: 0, mismatches: [], error: error.message };
    }
  } finally {
    ticking = false;
  }
  // The page re-reads this file by <script src>; rewriting it on every tick
  // would have the page revalidate a file whose content it already has. Only a
  // change in what the page acts on counts: the timestamp, the model list's age
  // and whether this very tick regenerated it are clock readings, not news.
  const signature = JSON.stringify({
    applies: status.applies,
    verify: status.verify,
    appliedToken: status.appliedToken,
    models: status.models && { ok: status.models.ok, count: status.models.count, error: status.models.error },
    error: status.error
  });
  if (signature !== lastSignature) {
    if (writeIfChanged(STATUS_FILE, statusScript(status))) lastSignature = signature;
  }
  return status;
}

function stop() {
  if (timer) {
    clearInterval(timer);
    timer = null;
  }
}

// MagpieModelsPricePlugin is the plugin function the host calls. It answers the
// hooks magpie runs (config only), and starts the apply loop once.
async function MagpieModelsPricePlugin(_input, _options) {
  if (!timer) {
    tick();
    timer = setInterval(tick, TICK_MS);
    if (timer.unref) timer.unref();
    process.once('exit', stop);
  }
  return {
    // magpie runs every plugin's config hook: answering nothing registers no
    // provider, no model and no middleware for this plugin
    config() {}
  };
}

module.exports = MagpieModelsPricePlugin;
module.exports.default = { id: 'models-price', server: MagpieModelsPricePlugin };
module.exports.server = MagpieModelsPricePlugin;
module.exports.__host = { tick, stop, refreshModels, refreshUsage, statusScript, STATUS_FILE, MODELS_FILE, USAGE_FILE, PAGE_DIR, TICK_MS };
